/** 依狀態篩選工單 */
export function filterWorkOrdersByStatus(status?: WorkOrderStatus): WorkOrder[] {
  if (!status) return mockWorkOrders;
  return mockWorkOrders.filter((workOrder) => workOrder.status === status);
}

/** 搜尋工單 */
export function searchWorkOrders(keyword: string): WorkOrder[] {
  const lowerKeyword = keyword.toLowerCase();
  return mockWorkOrders.filter(
    (workOrder) =>
      workOrder.workOrderNumber.toLowerCase().includes(lowerKeyword) ||
      workOrder.customerName.toLowerCase().includes(lowerKeyword) ||
      workOrder.icModel.toLowerCase().includes(lowerKeyword)
  );
}
